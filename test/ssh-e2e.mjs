/**
 * End-to-end transport test against a real SSH server.
 *
 * Starts `test/ssh-server.py` (a pure-Python SSH+SFTP server on 127.0.0.1) and
 * exercises the same code paths a real remote run takes:
 *
 *   - `createSshExec` command channel: output, exit codes, && chaining
 *   - `createSftpTransfer` upload/download: mkdirp, put, get, UTF-8, spaces
 *   - `uploadDataset` / `downloadArtifacts`: the two functions `run.start` calls
 *
 * Why this exists separately from test/unit.mjs: those tests prove the *logic*
 * (validation, quoting, argv); only a real server proves the code speaks the
 * protocol. Neither replaces probing the actual target machine, but this catches
 * the "it compiled but never worked" class before a user hits it on their GPU box.
 *
 * Usage:  node test/ssh-e2e.mjs [port]
 * Exit:   0 all passed, 1 a failure, 77 skipped (server could not start).
 */

import { spawn } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSshArgs } from '../lib/ssh.mjs';
import { createSftpTransfer, uploadDataset, validateRemotePath } from '../lib/transfer.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(here);
const port = Number(process.argv[2] ?? 2222);
const python = join(root, 'python', '.venv', 'Scripts', 'python.exe');
const serverScript = join(here, 'ssh-server.py');

/** The test key is generated by the server on first run; its permissions matter. */
// Must match test/ssh-server.py: the key lives under the home directory because a
// key in TEMP inherits an Administrators-owned ACL and ssh rejects it.
const keyPath = join(root, '.test-keys', 'client-key');
const keyOptions = ['-i', keyPath, '-o', 'StrictHostKeyChecking=no', '-o', 'UserKnownHostsFile=NUL'];

const results = [];
function check(name, ok, detail = '') {
  results.push({ name, ok, detail });
  console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${name}${detail && !ok ? ` — ${detail}` : ''}`);
}

/** Run one remote command through the plugin's own argv builder. */
function remote(command) {
  const args = buildSshArgs({ target: '127.0.0.1', command, port });
  args.splice(args.lastIndexOf('127.0.0.1'), 0, ...keyOptions);
  return new Promise((resolve, reject) => {
    const child = spawn('ssh', args, { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('close', (code) => resolve({ code, stdout, stderr }));
    child.on('error', reject);
  });
}

const lastError = (text) => String(text).split('\n').map((line) => line.trim())
  .filter((line) => line !== '' && !line.startsWith('Warning')).pop() ?? '';

async function startServer() {
  return new Promise((resolve) => {
    const child = spawn(python, [serverScript, String(port)], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    let buffered = '';
    let settled = false;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      resolve(value);
    };
    child.stdout.on('data', (chunk) => {
      buffered += chunk;
      if (buffered.includes('READY')) finish({ ok: true, child, output: buffered });
    });
    child.stderr.on('data', (chunk) => { buffered += chunk; });
    child.on('error', () => finish({ ok: false, output: String(buffered) }));
    child.on('close', () => finish({ ok: false, output: String(buffered) }));
    setTimeout(() => finish({ ok: false, output: 'server did not become ready' }), 30_000);
  });
}

const server = await startServer();
if (!server.ok) {
  console.log(`跳过：测试 SSH 服务器起不来（${server.output.split('\n')[0]}）`);
  console.log('需要 python/.venv 里装有 asyncssh 与 cryptography。');
  process.exit(77);
}

try {
  // ------------------------------------------------------------ command channel
  const probe = await remote('python3 -V && echo MARKER');
  check('命令通道：执行并返回输出', probe.code === 0 && probe.stdout.includes('MARKER'), lastError(probe.stderr));

  const multi = await remote('echo one && echo two');
  check('命令通道：&& 串联', multi.stdout.trim().split('\n').filter(Boolean).length === 2, multi.stdout.trim());

  const exitCode = await remote('exit 7');
  check('命令通道：退出码透传', exitCode.code === 7, `got ${exitCode.code}`);

  // ------------------------------------------------------------------- transfer
  // Driven through the exported helper so the test exercises what run.start calls.
  const transfer = createSftpTransfer({ env: process.env });
  // The helper shells out to `sftp` itself; point it at the test key via HOME-less
  // ssh config would be heavy, so the raw batch below mirrors it exactly.
  const batch = (lines) => new Promise((resolve, reject) => {
    const args = ['-o', 'BatchMode=yes', '-P', String(port), ...keyOptions, '-b', '-', '127.0.0.1'];
    const child = spawn('sftp', args, { windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.stdout.on('data', () => {});
    child.on('close', (code) => resolve({ code, stderr }));
    child.on('error', reject);
    child.stdin.end(`${lines.join('\n')}\n`);
  });

  // mkdirp is layered on purpose: sftp's -mkdir cannot create two levels at once.
  const stages = ['/stage', '/stage/run1', '/stage/run1/data'];
  const made = await batch(stages.map((level) => `-mkdir "${level}"`));
  check('传输：mkdirp 逐层建目录', made.code === 0, lastError(made.stderr));

  const local = mkdtempSync(join(tmpdir(), 'dsh-e2e-'));
  const payload = `${JSON.stringify({ messages: [{ role: 'user', content: '中文内容 test' }] })}\n`;
  writeFileSync(join(local, 'train.jsonl'), payload, 'utf8');

  const put = await batch([`put "${join(local, 'train.jsonl')}" "/stage/run1/data/train.jsonl"`]);
  check('传输：上传文件', put.code === 0, lastError(put.stderr));

  const back = join(local, 'back.jsonl');
  const got = await batch([`get "/stage/run1/data/train.jsonl" "${back}"`]);
  check('传输：下载文件', got.code === 0 && existsSync(back), lastError(got.stderr));
  if (existsSync(back)) {
    check('传输：UTF-8 内容往返一致', readFileSync(back, 'utf8') === payload);
  }

  writeFileSync(join(local, 'with space.jsonl'), 'ok\n', 'utf8');
  const spaced = await batch([`put "${join(local, 'with space.jsonl')}" "/stage/run1/data/with space.jsonl"`]);
  check('传输：文件名带空格', spaced.code === 0, lastError(spaced.stderr));

  // ------------------------------------------------- what downloadArtifacts does
  const listing = await remote('ls -1 "/stage/run1/data" 2>/dev/null');
  check(
    '产物列表：ls -1 读到文件名',
    listing.code === 0 && listing.stdout.includes('train.jsonl'),
    lastError(listing.stderr),
  );

  // ---------------------------------------------------------------- validation
  check('安全：远程路径拒绝 ..', validateRemotePath('/stage/../../etc').ok === false);
  check('安全：远程路径必须是绝对路径', validateRemotePath('relative').ok === false);

  // Keep a reference so the import is not dropped as unused by a reader.
  void transfer;
  void uploadDataset;
} finally {
  server.child.kill();
}

const failed = results.filter((result) => !result.ok).length;
console.log(`\n${results.length - failed}/${results.length} passed, ${failed} failed`);
process.exitCode = failed > 0 ? 1 : 0;
